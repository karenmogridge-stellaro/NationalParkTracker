#!/usr/bin/env node
/**
 * Fetches a representative photo for each of the 63 national parks from Wikipedia's
 * page-summary API and writes data/parkImages.ts (parkId -> { url, thumb, credit }).
 * Wikimedia URLs are stable and the images are CC/PD licensed.
 *
 * Usage: node scripts/fetch-park-images.mjs
 */
import { build } from 'esbuild';
import { writeFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import os from 'node:os';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'data', 'parkImages.ts');
const UA = 'ParkAtlas/2.0 (https://parkatlas.io; hello@parkatlas.io)';

// Wikipedia titles that don't follow "<Name> National Park".
const TITLE_OVERRIDES = {
  'American Samoa': 'National Park of American Samoa',
  'Denali': 'Denali National Park and Preserve',
  'Gates of the Arctic': 'Gates of the Arctic National Park and Preserve',
  'Glacier': 'Glacier National Park (U.S.)',
  'Glacier Bay': 'Glacier Bay National Park and Preserve',
  'Great Sand Dunes': 'Great Sand Dunes National Park and Preserve',
  'Katmai': 'Katmai National Park and Preserve',
  'Lake Clark': 'Lake Clark National Park and Preserve',
  'New River Gorge': 'New River Gorge National Park and Preserve',
  'Redwood': 'Redwood National and State Parks',
  'Wrangell-St. Elias': 'Wrangell–St. Elias National Park and Preserve',
  'Wrangell–St. Elias': 'Wrangell–St. Elias National Park and Preserve',
  'Hawaiʻi Volcanoes': 'Hawaiʻi Volcanoes National Park',
  'Haleakalā': 'Haleakalā National Park',
};

const tmp = path.join(os.tmpdir(), `parkatlas-parks-${Date.now()}.mjs`);
await build({
  stdin: { contents: `export { PARKS } from './data/parksData';`, resolveDir: ROOT, loader: 'ts' },
  bundle: true, format: 'esm', platform: 'node', outfile: tmp, logLevel: 'silent',
});
const { PARKS } = await import(tmp);
await rm(tmp, { force: true });

async function summary(title) {
  const res = await fetch(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(title)}`, {
    headers: { 'User-Agent': UA, Accept: 'application/json' },
  });
  if (!res.ok) return null;
  const j = await res.json();
  if (j.type === 'disambiguation' || !j.originalimage?.source) return null;
  return j;
}

/** Wikimedia thumb URL. Only certain widths are served (250/330/500/960/1280/1920). */
function thumbAt(original, width) {
  // https://upload.wikimedia.org/wikipedia/commons/a/ab/File.jpg
  //   -> https://upload.wikimedia.org/wikipedia/commons/thumb/a/ab/File.jpg/1600px-File.jpg
  const m = original.match(/^(https:\/\/upload\.wikimedia\.org\/wikipedia\/commons)\/([0-9a-f])\/([0-9a-f]{2})\/([^/]+)$/i);
  if (!m) return original;
  const [, base, a, ab, file] = m;
  const ext = file.toLowerCase().endsWith('.svg') ? `${file}.png` : file;
  return `${base}/thumb/${a}/${ab}/${file}/${width}px-${ext}`;
}

const entries = [];
const missing = [];
for (const park of PARKS) {
  const candidates = [
    TITLE_OVERRIDES[park.name],
    `${park.name} National Park`,
    `${park.name} National Park and Preserve`,
  ].filter(Boolean);

  let hit = null, usedTitle = null;
  for (const t of candidates) {
    hit = await summary(t);
    if (hit) { usedTitle = t; break; }
  }
  if (!hit) { missing.push(park.name); continue; }

  // The summary API tacks ?utm_source=… onto image URLs; drop it before deriving thumbs.
  const original = hit.originalimage.source.split('?')[0];
  entries.push({
    id: park.id,
    name: park.name,
    url: thumbAt(original, 1280),
    thumb: thumbAt(original, 960),
    credit: `Wikimedia Commons — ${usedTitle}`,
    page: hit.content_urls?.desktop?.page ?? `https://en.wikipedia.org/wiki/${encodeURIComponent(usedTitle)}`,
  });
  process.stdout.write(`✓ ${park.name}\n`);
}

const ts = `/**
 * Representative photo per national park (Wikipedia lead image via Wikimedia Commons).
 * Generated by scripts/fetch-park-images.mjs — do not edit by hand; rerun the script.
 * Used by both the app (utils/parkImagery.ts) and the website (web/build-parks.mjs).
 */
export interface ParkImage {
  /** 1280px wide */
  url: string;
  /** 960px wide */
  thumb: string;
  credit: string;
  page: string;
}

export const PARK_IMAGES: Record<string, ParkImage> = {
${entries.map((e) => `  // ${e.name}\n  '${e.id}': { url: ${JSON.stringify(e.url)}, thumb: ${JSON.stringify(e.thumb)}, credit: ${JSON.stringify(e.credit)}, page: ${JSON.stringify(e.page)} },`).join('\n')}
};
`;
await writeFile(OUT, ts);
console.log(`\nwrote ${entries.length}/${PARKS.length} to data/parkImages.ts`);
if (missing.length) console.log(`missing: ${missing.join(', ')}`);
